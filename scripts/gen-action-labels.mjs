// Writes src/projects/render/action-labels.ts from the `**Action label:**` line in each action's README — the one place a command says it carries a label.
import { readdirSync, readFileSync, existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ACTIONS_DIR = 'src/actions';
const OUT = 'src/projects/render/action-labels.ts';
const LABEL_LINE = /^\*\*Action label:\*\*.*data-final-action="(\w+)"/m;
const kebab = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

const commands = readdirSync(ACTIONS_DIR)
  .filter((folder) => existsSync(join(ACTIONS_DIR, folder, 'README.md')))
  .flatMap((folder) => {
    const command = readFileSync(join(ACTIONS_DIR, folder, 'README.md'), 'utf8').match(LABEL_LINE)?.[1];
    if (command && kebab(command) !== folder) throw new Error(`${folder}/README.md labels "${command}", not its own command`);
    return command ? [command] : [];
  })
  .sort();

writeFileSync(
  OUT,
  `// GENERATED by scripts/gen-action-labels.mjs from the **Action label:** line of each src/actions/*/README.md — do not edit.
import type { RenderProviderActions } from './types';

/** Put on the control whose press calls one of ACTION_LABEL_COMMANDS: data-final-action="cashPayment"; several — space-separated, string literal only. */
export const ACTION_LABEL_ATTRIBUTE = 'data-final-action';

/** Commands that move money, the cart, an order, a booking or stock. A flow that calls one carries the label on the control. */
export const ACTION_LABEL_COMMANDS = [
${commands.map((c) => `  '${c}',`).join('\n')}
] as const satisfies readonly (keyof RenderProviderActions)[];
`,
);
